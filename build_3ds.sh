#!/bin/bash
# Builds the 3DS port: RSDKv5U.elf/.3dsx and, with --cia, 3ds/out/SonicMania.cia.
# With --install [IP]: builds the CIA, uploads it to the running game's FTP server (port 5000) and
# installs it over the running build (SITE INSTALL); the game relaunches into it 10 s later.
# IP defaults to the last one used (.3ds_ftp_ip). The running game must be a dev-tools build.
# Needs devkitPro (devkitARM, libctru). libtheora for 3DS is taken from
# .deps/ when the portlibs lack it (see docs/PLAN.md, B0.1).
set -euo pipefail
cd "$(dirname "$0")"

# Windows: devkitPro's make and compilers only work from devkitPro's own MSYS2 shell. Run from another one (Git
# Bash), they get no environment at all (make sees DEVKITARM empty: "/3ds_rules: No such file"), so the script runs
# itself again there, with the variables it reads passed on by hand.
case "$(uname -s)" in
    MINGW*|MSYS*|CYGWIN*)
        if [ ! -d /opt/devkitpro ]; then
            DKP_BASH="${DEVKITPRO:-C:/devkitpro}/msys2/usr/bin/bash.exe"
            [ -x "$DKP_BASH" ] || { echo "build_3ds.sh: devkitPro's MSYS2 shell not found ($DKP_BASH)" >&2; exit 1; }
            FWD=()
            for v in DEV_TOOLS EXTRA_DEFINES MANIA3DS_CHANNEL; do
                [ -n "${!v+x}" ] && FWD+=("$v=${!v}")
            done
            exec "$DKP_BASH" -lc 'cd "$(cygpath -u "$1")" && shift && exec env "$@"' _ "$(cygpath -m "$PWD")" \
                "${FWD[@]}" ./build_3ds.sh "$@"
        fi
        ;;
esac

# Game is a symbolic link to the game logic's folder in the submodule. A Windows checkout without symbolic links
# (core.symlinks=false) leaves a text file holding that path: build from the path then.
GAME_DIR=Game
[ -f Game ] && GAME_DIR=$(tr -d '\r\n' < Game)
[ -f "$GAME_DIR/Game.c" ] || {
    echo "build_3ds.sh: no game logic in $GAME_DIR; run: git submodule update --init --recursive" >&2
    exit 1
}

export DEVKITPRO=${DEVKITPRO:-/opt/devkitpro}
export DEVKITARM=${DEVKITARM:-$DEVKITPRO/devkitARM}

L="$PWD/.deps/opt/devkitpro/portlibs/3ds"
LIBDIR="$DEVKITPRO/portlibs/3ds/lib/pkgconfig:$DEVKITPRO/portlibs/armv6k/lib/pkgconfig"
[ -d "$L/lib/pkgconfig" ] && LIBDIR="$L/lib/pkgconfig:$LIBDIR"

# The build's version (tools/version.sh: X.Y.Z on a tag, X.Y.Z-dev... on the release line) and channel
# (MANIA3DS_CHANNEL=beta|release, set by the release workflow; empty for local builds), for the updater and the
# OPTIONS tab. The header is rewritten only when it changes.
VERSION=$(sh tools/version.sh)
CHANNEL="${MANIA3DS_CHANNEL:-}"
LABEL="$VERSION"
[ "$CHANNEL" = beta ] && LABEL="$VERSION BETA"
VH=RSDKv5/RSDK/Dev/CTR/PortVersion.h
VTEXT=$(printf '#pragma once\n// Generated by build_3ds.sh (tools/version.sh); not in git.\n#define PORT_VERSION "%s"\n#define PORT_VERSION_LABEL "%s"\n#define PORT_IS_BETA %d\n' \
  "$VERSION" "$LABEL" "$([ "$CHANNEL" = beta ] && echo 1 || echo 0)")
# make does not track header dependencies: a new version drops the objects of the files that include it.
if [ "$(cat "$VH" 2>/dev/null)" != "$VTEXT" ]; then
  printf '%s\n' "$VTEXT" > "$VH"
  for f in $(grep -rl --include='*.cpp' 'PortVersion.h' RSDKv5); do
    rm -f "bin/obj/3DS/CTR/RSDKv5/${f%.cpp}.o"
  done
fi
export MANIA3DS_VERSION_LABEL="$LABEL" MANIA3DS_BUILD_VERSION="$VERSION"

# The updater's CA set (3ds/update-ca.pem, Mozilla's from curl.se) as a C++ string, rebuilt when the PEM changes.
CA=RSDKv5/RSDK/Dev/CTR/UpdateCa.inc
if [ ! -f "$CA" ] || [ 3ds/update-ca.pem -nt "$CA" ]; then
  { printf '// Generated by build_3ds.sh from 3ds/update-ca.pem; not in git.\nstatic const char kUpdateCa[] = R"PEM('; cat 3ds/update-ca.pem; printf ')PEM";\n'; } > "$CA"
  rm -f bin/obj/3DS/CTR/RSDKv5/RSDKv5/RSDK/Dev/CTR/Updater.o # make does not track headers
fi

# The Makefile does not add these by itself.
# DEV_TOOLS=0 leaves the FTP server and the perf timing out (production builds).
export DEFINES="-DRETRO_USE_MOD_LOADER=0 -DMANIA_DEV_TOOLS=${DEV_TOOLS:-1} -I./$GAME_DIR -I./$GAME_DIR/Objects ${EXTRA_DEFINES:-}"
# make does not rebuild objects when only a -D changes, and some of them (SCREEN_XMAX) change the layout of
# structures the engine and the game logic share: a stamp of the defines wipes the objects when they differ.
STAMP="bin/.defines"
STAMPED="$DEFINES rev2" # the engine revision passed to make below counts too
if [ "$(cat "$STAMP" 2>/dev/null)" != "$STAMPED" ]; then
  rm -rf bin
  mkdir -p bin
  printf '%s' "$STAMPED" > "$STAMP"
fi
# RETRO_REVISION=2: the engine of Sonic Mania Plus (the game's own), not v5U (Sonic Origins), whose Legacy engine for
# Sonic 1, 2 and CD Mania never runs but kept ~12 MB of static arrays in the 2DS's memory. The file keeps its name.
make PLATFORM=3DS RETRO_REVISION=2 RSDK_NAME=RSDKv5U GAME_NAME="$GAME_DIR" PKGCONFIG="env PKG_CONFIG_LIBDIR=$LIBDIR pkg-config --static" -j"$(nproc)"

if [ "${1:-}" = "--install" ]; then
  IP="${2:-$(cat .3ds_ftp_ip 2>/dev/null || true)}"
  [ -n "$IP" ] || { echo "usage: $0 --install <console IP>" >&2; exit 1; }
  (cd 3ds && ./build_cia.sh ../bin/3DS/CTR/RSDKv5U.elf)
  CIA=3ds/out/SonicMania.cia
  DIR="/3ds/Sonic Mania 3DS/update"
  URL="ftp://$IP:5000${DIR// /%20}/dev.cia"
  # ALLO announces the size (the bottom screen's progress bar); "-" runs SITE INSTALL after the upload.
  curl --fail --ftp-create-dirs -T "$CIA" "$URL" \
       -Q "+ALLO $(stat -c %s "$CIA")" -Q "-SITE INSTALL $DIR/dev.cia"
  echo "$IP" > .3ds_ftp_ip
  echo "Installed on $IP; the game relaunches in about 10 s."
elif [ "${1:-}" = "--cia" ]; then
  (cd 3ds && ./build_cia.sh ../bin/3DS/CTR/RSDKv5U.elf)
  echo "CIA: 3ds/out/SonicMania.cia"
fi
