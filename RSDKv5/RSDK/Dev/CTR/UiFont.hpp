#ifndef UI_FONT_CTR_HPP
#define UI_FONT_CTR_HPP

// 5x7 bitmap font of the owner's other ports (mzm's bottom screen, via sm-3ds' ui_font.c), ASCII part: upper case
// only (lower case maps to the same glyphs). 7 rows, bit 4 of a row is the leftmost column; text advances 6 px.
// Used for the top-screen FPS counter, which must look the same drawn by the GPU and by the software.

#include <stdint.h>
#include <stddef.h>

namespace UiFont
{

enum { GLYPH_W = 5, GLYPH_H = 7, ADVANCE = 6 };

inline const uint8_t *Glyph(unsigned char c)
{
    static const uint8_t digits[10][7] = {
        { 0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E }, { 0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E }, { 0x0E, 0x11, 0x01, 0x02, 0x04, 0x08, 0x1F },
        { 0x1E, 0x01, 0x01, 0x0E, 0x01, 0x01, 0x1E }, { 0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02 }, { 0x1F, 0x10, 0x10, 0x1E, 0x01, 0x01, 0x1E },
        { 0x0E, 0x10, 0x10, 0x1E, 0x11, 0x11, 0x0E }, { 0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08 }, { 0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E },
        { 0x0E, 0x11, 0x11, 0x0F, 0x01, 0x01, 0x0E },
    };
    static const uint8_t letters[26][7] = {
        { 0x0E, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11 }, { 0x1E, 0x11, 0x11, 0x1E, 0x11, 0x11, 0x1E }, { 0x0E, 0x11, 0x10, 0x10, 0x10, 0x11, 0x0E },
        { 0x1C, 0x12, 0x11, 0x11, 0x11, 0x12, 0x1C }, { 0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x1F }, { 0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x10 },
        { 0x0E, 0x11, 0x10, 0x13, 0x11, 0x11, 0x0F }, { 0x11, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11 }, { 0x0E, 0x04, 0x04, 0x04, 0x04, 0x04, 0x0E },
        { 0x07, 0x02, 0x02, 0x02, 0x02, 0x12, 0x0C }, { 0x11, 0x12, 0x14, 0x18, 0x14, 0x12, 0x11 }, { 0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1F },
        { 0x11, 0x1B, 0x15, 0x15, 0x11, 0x11, 0x11 }, { 0x11, 0x19, 0x15, 0x13, 0x11, 0x11, 0x11 }, { 0x0E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E },
        { 0x1E, 0x11, 0x11, 0x1E, 0x10, 0x10, 0x10 }, { 0x0E, 0x11, 0x11, 0x11, 0x15, 0x12, 0x0D }, { 0x1E, 0x11, 0x11, 0x1E, 0x14, 0x12, 0x11 },
        { 0x0E, 0x11, 0x10, 0x0E, 0x01, 0x11, 0x0E }, { 0x1F, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04 }, { 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E },
        { 0x11, 0x11, 0x11, 0x11, 0x11, 0x0A, 0x04 }, { 0x11, 0x11, 0x11, 0x15, 0x15, 0x15, 0x0A }, { 0x11, 0x11, 0x0A, 0x04, 0x0A, 0x11, 0x11 },
        { 0x11, 0x11, 0x0A, 0x04, 0x04, 0x04, 0x04 }, { 0x1F, 0x01, 0x02, 0x04, 0x08, 0x10, 0x1F },
    };
    static const uint8_t colon[7] = { 0x00, 0x0C, 0x0C, 0x00, 0x0C, 0x0C, 0x00 };
    static const uint8_t dot[7]   = { 0x00, 0x00, 0x00, 0x00, 0x00, 0x0C, 0x0C };
    static const uint8_t dash[7]  = { 0x00, 0x00, 0x00, 0x1F, 0x00, 0x00, 0x00 };
    static const uint8_t slash[7] = { 0x01, 0x02, 0x02, 0x04, 0x08, 0x08, 0x10 };
    if (c >= '0' && c <= '9')
        return digits[c - '0'];
    if (c >= 'A' && c <= 'Z')
        return letters[c - 'A'];
    if (c >= 'a' && c <= 'z')
        return letters[c - 'a'];
    switch (c) {
        case ':': return colon;
        case '.': return dot;
        case '-': return dash;
        case '/': return slash;
        default: return NULL;
    }
}

// Calls run(x, y, w) for every horizontal run of set pixels of `s` drawn at (x, y): one rectangle per run.
template <typename Run> inline void Runs(const char *s, int x, int y, Run run)
{
    for (; *s; ++s, x += ADVANCE) {
        const uint8_t *g = Glyph((unsigned char)*s);
        if (!g)
            continue;
        for (int r = 0; r < GLYPH_H; ++r) {
            const unsigned bits = g[r];
            for (int c = 0; c < GLYPH_W;) {
                if (!(bits & (0x10 >> c))) {
                    ++c;
                    continue;
                }
                int e = c;
                while (e < GLYPH_W && (bits & (0x10 >> e)))
                    ++e;
                run(x + c, y + r, e - c);
                c = e;
            }
        }
    }
}

} // namespace UiFont

#endif
