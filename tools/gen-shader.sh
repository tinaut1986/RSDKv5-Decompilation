#!/bin/bash
# Assembles a PICA vertex shader and writes it as a C array next to it: tools/gen-shader.sh x.v.pica
# -> x_shbin.h (name: x_shbin). Needs devkitPro's picasso.
set -euo pipefail
SRC="$1"; BASE=$(basename "$SRC" .v.pica); DIR=$(dirname "$SRC")
/opt/devkitpro/tools/bin/picasso -o "/tmp/$BASE.shbin" "$SRC"
python3 - "/tmp/$BASE.shbin" "$DIR/${BASE}_shbin.h" "${BASE}_shbin" <<'PY'
import sys
d=open(sys.argv[1],'rb').read()
d+=b'\0'*(-len(d)%4)
w=[int.from_bytes(d[i:i+4],'little') for i in range(0,len(d),4)]
with open(sys.argv[2],'w') as f:
    f.write('// Generated by tools/gen-shader.sh; do not edit.\n#pragma once\n#include <stdint.h>\n')
    f.write('static const uint32_t %s[%d] = {\n'%(sys.argv[3],len(w)))
    for i in range(0,len(w),8): f.write('    '+', '.join('0x%08x'%x for x in w[i:i+8])+',\n')
    f.write('};\n')
print(len(d),'bytes ->',sys.argv[2])
PY
